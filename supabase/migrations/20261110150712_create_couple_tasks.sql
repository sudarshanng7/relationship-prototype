-- Purple Garden database change
-- Feature: Shared List
-- Purpose: Real-time collaborative groceries, home tasks, errands and other shared items
-- Data classification: Couple-scoped user content
-- Security boundary: RLS membership checks via private.user_couple_ids()
-- Introduced: 2026-11-10

-- 1. Safely create or reuse private updated_at trigger function
CREATE OR REPLACE FUNCTION private.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

-- Revoke direct execution from client roles since this function is only executed via triggers
REVOKE ALL ON FUNCTION private.set_updated_at() FROM PUBLIC, anon, authenticated;

COMMENT ON FUNCTION private.set_updated_at() IS 'Internal trigger helper for maintaining updated_at timestamps on mutable records. Not a client-callable RPC.';

-- 2. Create public.couple_tasks table
CREATE TABLE public.couple_tasks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  couple_id uuid NOT NULL REFERENCES public.couples(id) ON DELETE CASCADE,
  created_by uuid DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE SET NULL,
  title text NOT NULL,
  category text NOT NULL DEFAULT 'other',
  status text NOT NULL DEFAULT 'open',
  completed_at timestamptz NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT couple_tasks_title_check CHECK (
    title = btrim(title) AND
    char_length(title) >= 1 AND
    char_length(title) <= 120
  ),
  CONSTRAINT couple_tasks_category_check CHECK (
    category IN ('groceries', 'home', 'errands', 'other')
  ),
  CONSTRAINT couple_tasks_status_check CHECK (
    status IN ('open', 'completed')
  ),
  CONSTRAINT couple_tasks_completion_consistency CHECK (
    (status = 'open' AND completed_at IS NULL) OR
    (status = 'completed' AND completed_at IS NOT NULL)
  )
);

-- 3. Automatic updated_at trigger
CREATE TRIGGER on_couple_task_updated
BEFORE UPDATE ON public.couple_tasks
FOR EACH ROW
EXECUTE FUNCTION private.set_updated_at();

-- 4. Indexes for couple queries, status filtering, category filtering, chronological sorting, and foreign keys
CREATE INDEX couple_tasks_couple_id_idx ON public.couple_tasks USING btree (couple_id);
CREATE INDEX couple_tasks_couple_id_status_idx ON public.couple_tasks USING btree (couple_id, status);
CREATE INDEX couple_tasks_couple_id_category_idx ON public.couple_tasks USING btree (couple_id, category);
CREATE INDEX couple_tasks_couple_id_created_at_desc_idx ON public.couple_tasks USING btree (couple_id, created_at DESC);
CREATE INDEX couple_tasks_created_by_idx ON public.couple_tasks USING btree (created_by);

-- 5. Row Level Security (RLS)
ALTER TABLE public.couple_tasks ENABLE ROW LEVEL SECURITY;

-- SELECT: Allowed only when couple_id belongs to the authenticated user's active couple
CREATE POLICY "Couple members can read tasks"
ON public.couple_tasks
FOR SELECT TO authenticated
USING (couple_id IN (SELECT private.user_couple_ids()));

-- INSERT: Couple ID must belong to caller's couple and created_by must equal auth.uid()
CREATE POLICY "Couple members can insert tasks"
ON public.couple_tasks
FOR INSERT TO authenticated
WITH CHECK (
  couple_id IN (SELECT private.user_couple_ids())
  AND created_by = (SELECT auth.uid())
);

-- UPDATE: Both members may update tasks belonging to their couple
CREATE POLICY "Couple members can update tasks"
ON public.couple_tasks
FOR UPDATE TO authenticated
USING (couple_id IN (SELECT private.user_couple_ids()))
WITH CHECK (couple_id IN (SELECT private.user_couple_ids()));

-- DELETE: Both members may delete tasks belonging to their couple
CREATE POLICY "Couple members can delete tasks"
ON public.couple_tasks
FOR DELETE TO authenticated
USING (couple_id IN (SELECT private.user_couple_ids()));

-- 6. Column-level permissions
REVOKE ALL ON public.couple_tasks FROM PUBLIC, anon;
REVOKE ALL ON public.couple_tasks FROM authenticated;

GRANT SELECT, DELETE ON public.couple_tasks TO authenticated;

GRANT INSERT (
  couple_id,
  title,
  category
) ON public.couple_tasks TO authenticated;

GRANT UPDATE (
  title,
  category,
  status,
  completed_at
) ON public.couple_tasks TO authenticated;

GRANT ALL ON public.couple_tasks TO service_role;

-- 7. Documentation comments
COMMENT ON TABLE public.couple_tasks IS 'Real-time collaborative task and grocery list items scoped to connected couples in Purple Garden.';

COMMENT ON COLUMN public.couple_tasks.id IS 'Unique task identifier generated by the database.';
COMMENT ON COLUMN public.couple_tasks.couple_id IS 'Foreign key referencing the couple space that owns this task.';
COMMENT ON COLUMN public.couple_tasks.created_by IS 'Auth user ID of the partner who created this task (null if user is removed).';
COMMENT ON COLUMN public.couple_tasks.title IS 'Trimmed, non-empty task description limited to 1 through 120 characters.';
COMMENT ON COLUMN public.couple_tasks.category IS 'Task category: groceries, home, errands, or other; defaults to other when omitted.';
COMMENT ON COLUMN public.couple_tasks.status IS 'Task progress status: open or completed.';
COMMENT ON COLUMN public.couple_tasks.completed_at IS 'Timestamp when the task was marked completed; null when open.';
COMMENT ON COLUMN public.couple_tasks.created_at IS 'Timestamp when the task was created.';
COMMENT ON COLUMN public.couple_tasks.updated_at IS 'Timestamp when the task was last updated, maintained by trigger.';

COMMENT ON POLICY "Couple members can read tasks" ON public.couple_tasks IS 'Restricts task reads to authenticated members of the couple that owns the task.';
COMMENT ON POLICY "Couple members can insert tasks" ON public.couple_tasks IS 'Ensures tasks can only be created by an authenticated couple member for their active couple space with created_by set to auth.uid().';
COMMENT ON POLICY "Couple members can update tasks" ON public.couple_tasks IS 'Allows either partner in the couple to edit task fields, preventing reassignment to another couple.';
COMMENT ON POLICY "Couple members can delete tasks" ON public.couple_tasks IS 'Allows either partner in the couple to delete tasks belonging to their relationship space.';

-- 8. Realtime Replication
ALTER TABLE ONLY public.couple_tasks REPLICA IDENTITY FULL;

-- Note: The client-side subscription filter (couple_id=eq.<id>) is an optimization for message delivery
-- and does not constitute a security boundary. Row-level security (RLS) policies on public.couple_tasks
-- provide the authoritative security boundary preventing cross-couple unauthorized access.
ALTER PUBLICATION supabase_realtime ADD TABLE public.couple_tasks;
